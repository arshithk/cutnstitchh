/**
 * Returns merged keyword lists for any category or product slug.
 */
export function getKeywordsForCategory(categorySlug: string): string[] {
  const normalized = categorySlug.toLowerCase().replace(/-t-shirts?$/, "");
  const specific = CATEGORY_KEYWORDS[normalized] || CATEGORY_KEYWORDS[categorySlug] || [];
  return Array.from(new Set([...specific, ...MASTER_GLOBAL_KEYWORDS.slice(0, 15)]));
}

/**
 * Generates technical and contextual keywords for specific product variants.
 */
export function getKeywordsForProduct(name: string, fabric?: string, gsm?: string): string[] {
  const kws = new Set<string>();
  const n = (name || "").toLowerCase();
  const f = (fabric || "").toLowerCase();
  const g = (gsm || "").toLowerCase();

  // Core base
  kws.add("apparel manufacturer in bangalore");
  kws.add("custom apparel manufacturer india");
  kws.add("low moq clothing manufacturer india");

  if (n.includes("oversized") || n.includes("drop shoulder")) {
    CATEGORY_KEYWORDS.oversized.forEach((k) => kws.add(k));
  } else if (n.includes("polo") || n.includes("collared") || n.includes("tipping")) {
    CATEGORY_KEYWORDS.polo.forEach((k) => kws.add(k));
  } else if (n.includes("hoodie") || n.includes("hooded")) {
    CATEGORY_KEYWORDS.hoodie.forEach((k) => kws.add(k));
  } else if (n.includes("sweatshirt") || n.includes("crewneck")) {
    CATEGORY_KEYWORDS.sweatshirt.forEach((k) => kws.add(k));
  } else if (n.includes("short")) {
    CATEGORY_KEYWORDS.shorts.forEach((k) => kws.add(k));
  } else if (n.includes("jogger") || n.includes("track")) {
    CATEGORY_KEYWORDS.joggers.forEach((k) => kws.add(k));
  } else {
    CATEGORY_KEYWORDS["regular-fit"].forEach((k) => kws.add(k));
  }

  // Fabric specific
  if (f.includes("cotton")) {
    kws.add("100% super combed cotton");
    kws.add("bio-washed cotton fabric");
    kws.add("dtf and screen printing friendly");
  }
  if (f.includes("french terry")) {
    kws.add("french terry cotton manufacturer");
    kws.add("loopknit interior heavy drape");
  }
  if (f.includes("fleece")) {
    kws.add("brushed fleece warm fabric");
    kws.add("anti-shrink fleece manufacturer");
  }
  if (f.includes("pique") || f.includes("honeycomb") || f.includes("matty")) {
    kws.add("pique honeycomb collar fabric");
    kws.add("colorfast polo knit");
  }
  if (f.includes("dri fit") || f.includes("polyester") || f.includes("mars")) {
    kws.add("dri-fit moisture wicking fabric");
    kws.add("quick dry sports performance wear");
    kws.add("sublimation printing polyester");
  }
  if (f.includes("lycra") || f.includes("stretch")) {
    kws.add("4-way stretch lycra athletic fabric");
    kws.add("squat proof workout fabric");
  }

  // GSM specific
  if (g.includes("180")) kws.add("180 gsm cotton t-shirt manufacturer bangalore");
  if (g.includes("240")) kws.add("240 gsm heavyweight oversized t-shirt");
  if (g.includes("220")) kws.add("220 gsm pique polo t-shirt");
  if (g.includes("300")) kws.add("300 gsm fleece hoodie wholesale");
  if (g.includes("340")) kws.add("340 gsm heavy winter hoodie manufacturer");

  return Array.from(kws);
}

